  @doc """
  Captures a task into the default project: a bare title, everything else
  defaulted by the schema (state `:inbox`, empty body).

  Deliberately not "the active project". A capture with no project named lands
  somewhere fixed and predictable, so `tend add` from any shell behaves the
  same way every time; callers that know where a task belongs say so through
  `add_task_in/3`. This is `AGENTS.md` §2 -- capture requires nothing,
  organization is a later, separate act -- applied to the project as well as
  to the state.
  """
  @spec add_task(t(), String.t()) :: {:ok, Task.t()} | {:error, Tend.Error.t()}
  def add_task(store, title), do: add_task_in(store, Project.default_id(), title)

  @doc """
  Captures a task into a named project, for `tend add -p` and the TUI's
  quick-add against the selected project.
  """
  @spec add_task_in(t(), integer(), String.t()) :: {:ok, Task.t()} | {:error, Tend.Error.t()}
  def add_task_in(store, project_id, title) when is_integer(project_id) do
    with {:ok, normalized} <- Task.normalize_title(title) do
      insert_task(store, @create_task, [normalized, project_id])
    end
  end

  @doc """
  Captures a task that arrives with context already attached (an imported Jira
  ticket, say): title plus a markdown body, everything else defaulted by the
  schema.
  """
  @spec add_task_with_body(t(), String.t(), String.t()) ::
          {:ok, Task.t()} | {:error, Tend.Error.t()}
  def add_task_with_body(store, title, body) do
    add_task_with_body_in(store, Project.default_id(), title, body)
  end

  @doc """
  `add_task_with_body/3` against an explicit project.
  """
  @spec add_task_with_body_in(t(), integer(), String.t(), String.t()) ::
          {:ok, Task.t()} | {:error, Tend.Error.t()}
  def add_task_with_body_in(store, project_id, title, body)
      when is_integer(project_id) and is_binary(body) do
    with {:ok, normalized} <- Task.normalize_title(title) do
      insert_task(store, @create_task_with_body, [normalized, body, project_id])
    end
  end

  # -- reads -----------------------------------------------------------------

  @doc """
  Loads one task by id.

  A task that is not there is `{:error, {:task_not_found, id}}`. Go has no
  `ErrTaskNotFound`: its `GetTask` wraps whatever `database/sql` returned, and
  a missing row arrives as `sql.ErrNoRows`. exqlite has no such error -- an
  empty result is an empty list -- so the port has to name the condition
  itself rather than let "no rows" and "the query failed" read alike.
  """
  @spec get_task(t(), integer()) :: {:ok, Task.t()} | {:error, Tend.Error.t()}
  def get_task(store, id) when is_integer(id) do
    case query(store, @get_task, [id], "loading task #{id}") do
      {:ok, [row]} -> Row.to_task(row)
      {:ok, []} -> {:error, {:task_not_found, id}}
      {:error, reason} -> {:error, reason}
    end
  end

