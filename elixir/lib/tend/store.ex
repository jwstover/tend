  # -- transactions ----------------------------------------------------------

  @doc """
  Runs `fun` inside a transaction, committing its result and rolling back on
  `{:error, reason}`.

  The port of `inTx` in `internal/store/projects.go`, and public for the same
  reason Go's is package-wide: every multi-statement invariant in the store
  goes through it. `tasks.project_id` carries no foreign key (see migration
  00007), so the writes that stand in for one have to be atomic themselves.

  Go's helper takes a `func(q *gen.Queries) error` and hands it a `Queries`
  bound to the transaction. exqlite has no such object -- a transaction is a
  property of the connection, not a handle -- so `fun` is handed the store
  itself and simply calls the ordinary functions on it.

  A raise, a throw or an exit inside `fun` rolls back and is re-raised
  unchanged, which is what Go's `defer tx.Rollback()` buys it: the store's
  connection is long-lived, so a transaction left open by an unwinding caller
  would block every later write on it.

  Nothing in the task surface is multi-statement, so this has no caller on
  this branch; the functions that need it -- `SetProject`, `SetParent`,
  `SetTags`, `DeleteProject` -- are later parts of the store port.
  """
  @spec transaction(t(), (t() -> result)) :: result | {:error, Tend.Error.t()} when result: var
  def transaction(%__MODULE__{} = store, fun) when is_function(fun, 1) do
    with :ok <- statement(store, "BEGIN", "beginning transaction") do
      try do
        case fun.(store) do
          {:error, reason} ->
            rollback(store)
            {:error, reason}

          result ->
            case statement(store, "COMMIT", "committing transaction") do
              :ok -> result
              {:error, reason} -> {:error, rollback_and(store, reason)}
            end
        end
      catch
        kind, reason ->
          rollback(store)
          :erlang.raise(kind, reason, __STACKTRACE__)
      end
    end
  end

  defp ensure_directory(path) do
    case path |> Path.dirname() |> File.mkdir_p() do
      :ok -> :ok
      {:error, reason} -> {:error, {:db_directory_failed, Path.dirname(path), reason}}
    end
  end

  defp connect(path) do
    case Sqlite3.open(path) do
      {:ok, conn} -> {:ok, conn}
      {:error, reason} -> {:error, {:db_open_failed, path, reason}}
    end
  end

  defp pragmas(conn) do
    Enum.reduce_while(
      [
        "PRAGMA journal_mode = WAL",
        "PRAGMA busy_timeout = 5000",
        "PRAGMA foreign_keys = ON"
      ],
      :ok,
      fn sql, :ok ->
        case Sqlite3.execute(conn, sql) do
          :ok -> {:cont, :ok}
          {:error, reason} -> {:halt, {:error, {:pragma_failed, sql, reason}}}
        end
      end
    )
  end

  # The port of Go's projectFilter. sqlc's nullable named argument becomes an
  # untyped interface{} there, so nil means "every project" and a bare int64
  # scopes the query; exqlite binds nil as SQL NULL and an integer as itself,
  # which is the same two cases against the same `?1 IS NULL OR ...` clause.
  # The guard is the point: without it a project id of the wrong shape would
  # bind as something `?1 IS NULL` reads as present, quietly scoping the query
  # to nothing rather than failing.
  defp project_filter(nil), do: nil
  defp project_filter(id) when is_integer(id), do: id

  # `INSERT ... RETURNING` yields exactly one row. Anything else means the
  # statement above stopped being the insert it is copied from, which is worth
  # an error rather than a match failure three frames away.
  defp insert_task(store, sql, params) do
    case query(store, sql, params, "inserting task") do
      {:ok, [row]} -> Row.to_task(row)
      {:ok, rows} -> {:error, {:query_failed, "inserting task", {:rows_returned, length(rows)}}}
      {:error, reason} -> {:error, reason}
    end
  end

  defp normalize_due(nil), do: {:ok, nil}
  defp normalize_due(due) when is_binary(due), do: Task.normalize_date(due)

  # Best effort, exactly as Go's `defer func() { _ = tx.Rollback() }()` is: the
  # caller is already getting the real failure, and a rollback that itself
  # fails has nothing better to say. After a successful COMMIT it is a no-op
  # error ("cannot rollback - no transaction is active"), which is why the
  # result is discarded rather than reported.
  defp rollback(store) do
    _ = statement(store, "ROLLBACK", "rolling back transaction")
    :ok
  end

  defp rollback_and(store, reason) do
    rollback(store)
    reason
  end

  # The second half of SessionStatuses: the active runs, newest-first, laid
  # over the per-task session statuses. `seen` is Go's `fromRun` map.
  defp overlay_runs(rows, statuses) do
    {statuses, _seen} = Enum.reduce(rows, {statuses, MapSet.new()}, &overlay_run/2)
    statuses
  end

  # Go reads r.State off a gen.WorkflowRun as a raw string and hands it to
  # workflow.RunState(r.State).SessionStatus(), which answers for any value.
  # RunState.parse/1 is strict, so a state the schema's CHECK does not allow
  # lands on the same "says nothing" answer a terminal one does -- and, like a
  # terminal one, does not claim the task either, so an older active run still
  # gets its turn.
  defp overlay_run(row, {statuses, seen} = unchanged) do
    [_id, _workflow_id, task_id, _cwd, state | _rest] = row

    with false <- MapSet.member?(seen, task_id),
         {:ok, run_state} <- RunState.parse(state),
         {:ok, status} <- RunState.session_status(run_state) do
      # A paused run claims the task either way, but yields its own status to
      # the task's session when there is one: during a takeover the
      # interactive session's hooks say more than "paused" does.
      if run_state == :paused and Map.has_key?(statuses, task_id) do
        {statuses, MapSet.put(seen, task_id)}
      else
        {Map.put(statuses, task_id, status), MapSet.put(seen, task_id)}
      end
    else
      # Already spoken for by a newer run, or a run whose state has no status.
      _skip -> unchanged
    end
  end

  # Runs a statement for effect. Go's generated :exec methods discard the
  # sql.Result, and so does this: not one caller in the task surface looks at
  # the row count.
  defp execute(store, sql, params, context) do
    with {:ok, _rows} <- query(store, sql, params, context), do: :ok
  end

  # Prepare, bind, run, release. The statement is released on both paths --
  # exqlite hands back a NIF resource, and leaking one holds the compiled
  # statement (and its read transaction) open.
  defp query(%__MODULE__{conn: conn}, sql, params, context) do
    case Sqlite3.prepare(conn, sql) do
      {:ok, statement} ->
        result =
          with :ok <- Sqlite3.bind(statement, params) do
            Sqlite3.fetch_all(conn, statement)
          end

        Sqlite3.release(conn, statement)
        tag(result, context)

      {:error, reason} ->
        {:error, {:query_failed, context, reason}}
    end
  end

  # BEGIN/COMMIT/ROLLBACK take no parameters and return no rows, so they go
  # through sqlite3_exec the way the migrator's statements do.
  defp statement(%__MODULE__{conn: conn}, sql, context) do
    case Sqlite3.execute(conn, sql) do
      :ok -> :ok
      {:error, reason} -> {:error, {:query_failed, context, reason}}
    end
  end

  # Every driver failure is wrapped with the label its Go call site passes to
  # fmt.Errorf, so the two trees' messages read the same.
  defp tag({:ok, rows}, _context), do: {:ok, rows}
  defp tag({:error, reason}, context), do: {:error, {:query_failed, context, reason}}
end
