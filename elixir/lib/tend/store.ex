  FROM tasks t
  JOIN states s ON s.name = t.state
  WHERE (s.is_terminal = 0 OR t.state = 'done' OR s.hidden_by_default = 1)
    AND (t.snooze_until IS NULL OR t.snooze_until <= date('now'))
