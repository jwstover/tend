  @doc """
  Loads one task by id.

  A task that is not there is `{:error, {:task_not_found, id}}`. Go has no
  `ErrTaskNotFound`: its `GetTask` wraps whatever `database/sql` returned, and
  a missing row arrives as `sql.ErrNoRows`. exqlite has no such error -- an
  empty result is an empty list -- so the port has to name the condition
  itself rather than let "no rows" and "the query failed" read alike.
  """
  @spec get_task(t(), integer()) :: {:ok, Task.t()} | {:error, Tend.Error.t()}
  def get_task(store, id) when is_integer(id) do
    case query(store, @get_task, [id], "loading task #{id}") do
      {:ok, [row]} -> Row.to_task(row)
      {:ok, []} -> {:error, {:task_not_found, id}}
      {:error, reason} -> {:error, reason}
    end
  end

