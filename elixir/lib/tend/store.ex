  @spec child_counts(t()) :: {:ok, %{integer() => ChildCount.t()}} | {:error, Tend.Error.t()}
  def child_counts(store) do
    with {:ok, rows} <- query(store, @list_child_counts, [], "listing child counts") do
      counts =
        for [parent_id, total, done] <- rows, parent_id != nil, into: %{} do
          {parent_id, %ChildCount{done: done, total: total}}
        end

      {:ok, counts}
    end
  end

  @doc """
  Each task's agent status, keyed by task id -- what the list row renders so a
  background session's state is visible without opening the task.

  A task with a workflow run in a non-terminal state takes the run's state,
  mapped into the session vocabulary (`Tend.Workflow.RunState.session_status/1`):
  a headless run has no tmux pane for the poller to classify and its step
  sessions are `:starting` for most of their life, so the run row is the
  better signal. The one exception is a paused run, which yields to the task's
  latest session status when there is one -- during a takeover the interactive
  session's own hooks say more than "paused" does -- and reads `:idle` only
  when the task has no session at all. A task with only ended runs falls
  through to its sessions.

  The session query returns every session oldest-first and the map keeps the
  last write per task, which is the most recent one. That is cheaper to reason
  about than a correlated `MAX()` subquery and needs no tiebreak rule for two
  sessions sharing a timestamp, since the ordering already falls back to id.
  Active runs come newest-first, so the first run seen per task is the one
  that wins.
  """
  @spec session_statuses(t()) ::
          {:ok, %{integer() => SessionStatus.t()}} | {:error, Tend.Error.t()}
  def session_statuses(store) do
    with {:ok, session_rows} <-
           query(store, @list_session_statuses, [], "listing session statuses"),
         {:ok, run_rows} <- query(store, @list_active_runs, [], "listing active runs") do
      statuses =
        for [task_id, status] <- session_rows, into: %{} do
          {task_id, SessionStatus.parse(status)}
        end

      {:ok, overlay_runs(run_rows, statuses)}
    end
